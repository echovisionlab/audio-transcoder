import { mkdir, readFile, writeFile } from 'node:fs/promises';

const packageJsonUrl = new URL('../package.json', import.meta.url);
const manifestUrl = new URL('../codec-assets/manifest.json', import.meta.url);
const outputUrl = new URL(
  '../src/generated/codec-asset-metadata.ts',
  import.meta.url,
);

const packageJson = JSON.parse(await readFile(packageJsonUrl, 'utf8'));
const stagedManifest = JSON.parse(await readFile(manifestUrl, 'utf8'));

const packageVersion = requireExactVersion(packageJson.version, 'package.json');
if (stagedManifest.version !== packageVersion) {
  throw new Error(
    `codec-assets/manifest.json version ${String(stagedManifest.version)} must match package.json version ${packageVersion}.`,
  );
}
if (stagedManifest.schemaVersion !== 1) {
  throw new Error(
    `Unsupported codec asset manifest schema: ${String(stagedManifest.schemaVersion)}`,
  );
}
if (!Number.isSafeInteger(stagedManifest.abiVersion) || stagedManifest.abiVersion < 1) {
  throw new Error('Codec asset ABI version must be a positive integer.');
}
if (
  stagedManifest.assets === null ||
  typeof stagedManifest.assets !== 'object' ||
  Array.isArray(stagedManifest.assets)
) {
  throw new Error('Codec asset manifest assets must be an object.');
}

const manifest = stagedManifest;
const output = `// Generated by scripts/generate-codec-asset-metadata.mjs. Do not edit.\n\nexport const GENERATED_CODEC_ASSET_REPOSITORY = 'echovisionlab/audio-transcoder';\nexport const GENERATED_CODEC_ASSET_BASE_PATH = 'codec-assets';\nexport const GENERATED_CODEC_ASSET_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n`;

await mkdir(new URL('./', outputUrl), { recursive: true });
await writeFile(outputUrl, output, 'utf8');

function requireExactVersion(value, source) {
  if (
    typeof value !== 'string' ||
    !/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?$/.test(
      value,
    )
  ) {
    throw new Error(`${source} must declare an exact SemVer version.`);
  }
  return value;
}
