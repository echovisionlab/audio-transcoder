import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const [inputArgument, outputArgument] = process.argv.slice(2);
if (inputArgument === undefined || outputArgument === undefined) {
  throw new Error(
    'Usage: node scripts/ogg-opus-embed-wasm.mjs <input.wasm> <output.ts>',
  );
}

const input = resolve(inputArgument);
const output = resolve(outputArgument);
const wasm = await readFile(input);
const sha256 = createHash('sha256').update(wasm).digest('hex');
const base64 = wasm.toString('base64');
const module = await WebAssembly.compile(wasm);
const source = `/* This file is generated by scripts/ogg-opus-build-wasm.sh. */
export const OGG_OPUS_WASM_SHA256 = '${sha256}';

const OGG_OPUS_WASM_BASE64 =
  '${base64}';

/** Returns a fresh copy so WebAssembly compilation cannot mutate cached data. */
export function getOggOpusWasmBytes(): Uint8Array<ArrayBuffer> {
  const binary = atob(OGG_OPUS_WASM_BASE64);
  const bytes = new Uint8Array(binary.length);
  for (let index = 0; index < binary.length; index += 1) {
    bytes[index] = binary.charCodeAt(index);
  }
  return bytes;
}
`;

await writeFile(output, source);
console.log(`Embedded ${wasm.byteLength} bytes (${sha256}) in ${output}`);
console.log('WASM imports:', WebAssembly.Module.imports(module));
