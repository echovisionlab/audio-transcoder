import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const [qualityArgument, inputArgument, outputArgument] = process.argv.slice(2);
if (
  !['best', 'balanced', 'fast'].includes(qualityArgument) ||
  inputArgument === undefined ||
  outputArgument === undefined
) {
  throw new Error(
    'Usage: node scripts/resampler-embed-wasm.mjs <best|balanced|fast> <input.wasm> <output.ts>',
  );
}

const input = resolve(inputArgument);
const output = resolve(outputArgument);
const wasm = await readFile(input);
const sha256 = createHash('sha256').update(wasm).digest('hex');
const base64 = wasm.toString('base64');
const module = await WebAssembly.compile(wasm);
const source = `/* This file is generated by scripts/resampler-build-wasm.sh. */
export const RESAMPLER_WASM_SHA256 = '${sha256}';

const RESAMPLER_WASM_BASE64 =
  '${base64}';

/** Returns a fresh copy of the ${qualityArgument} libsamplerate module. */
export function getResamplerWasmBytes(): Uint8Array<ArrayBuffer> {
  const binary = atob(RESAMPLER_WASM_BASE64);
  const bytes = new Uint8Array(binary.length);
  for (let index = 0; index < binary.length; index += 1) {
    bytes[index] = binary.charCodeAt(index);
  }
  return bytes;
}
`;

await writeFile(output, source);
console.log(
  `Embedded ${qualityArgument} ${wasm.byteLength} bytes (${sha256}) in ${output}`,
);
console.log('WASM imports:', WebAssembly.Module.imports(module));
