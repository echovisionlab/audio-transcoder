import { mkdir, readFile, writeFile } from 'node:fs/promises';

const packageJsonUrl = new URL('../package.json', import.meta.url);
const outputUrl = new URL(
  '../src/generated/package-metadata.ts',
  import.meta.url,
);

const packageJson = JSON.parse(await readFile(packageJsonUrl, 'utf8'));

function requireNonEmptyString(value, fieldName) {
  if (typeof value !== 'string' || value.trim() === '') {
    throw new TypeError(`package.json ${fieldName} must be a non-empty string`);
  }

  return value;
}

const packageName = requireNonEmptyString(packageJson.name, 'name');
const packageVersion = requireNonEmptyString(packageJson.version, 'version');
const output = `// Generated by scripts/generate-package-metadata.mjs. Do not edit.\n\nexport const GENERATED_PACKAGE_NAME = ${JSON.stringify(packageName)};\nexport const GENERATED_PACKAGE_VERSION = ${JSON.stringify(packageVersion)};\n`;

await mkdir(new URL('./', outputUrl), { recursive: true });
await writeFile(outputUrl, output, 'utf8');
